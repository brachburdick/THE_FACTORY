#!/usr/bin/env python3
"""
Failure-to-eval pipeline (tf-090).

Reads .agent/incidents.jsonl, clusters by failure type, and generates
draft eval specs in .agent/evals/ for patterns recurring 3+ times.

Usage:
    .venv/bin/python scripts/incidents-to-evals.py              # Generate drafts
    .venv/bin/python scripts/incidents-to-evals.py --dry-run    # Preview without writing
    .venv/bin/python scripts/incidents-to-evals.py --threshold 5 # Min occurrences
"""

import argparse
import json
import re
import sys
from collections import Counter, defaultdict
from datetime import datetime
from pathlib import Path
from textwrap import dedent

ROOT = Path(__file__).resolve().parent.parent
INCIDENTS_FILE = ROOT / ".agent" / "incidents.jsonl"
EVALS_DIR = ROOT / ".agent" / "evals"

# ---------------------------------------------------------------------------
# Clustering
# ---------------------------------------------------------------------------

def normalize_summary(summary: str) -> str:
    """Collapse numbers to get a stable cluster key."""
    # "Budget exhausted: 11 mutations (limit 10)" → "Budget exhausted: N mutations (limit N)"
    return re.sub(r'\b\d+\b', 'N', summary)


def load_incidents() -> list[dict]:
    if not INCIDENTS_FILE.exists():
        return []
    incidents = []
    for line in INCIDENTS_FILE.read_text().splitlines():
        line = line.strip()
        if not line:
            continue
        try:
            incidents.append(json.loads(line))
        except json.JSONDecodeError:
            continue
    return incidents


def cluster_incidents(incidents: list[dict]) -> dict[str, list[dict]]:
    """Group incidents by normalized summary."""
    clusters: dict[str, list[dict]] = defaultdict(list)
    for inc in incidents:
        key = normalize_summary(inc.get("summary", "unknown"))
        clusters[key].append(inc)
    return dict(clusters)


# ---------------------------------------------------------------------------
# Eval spec generation
# ---------------------------------------------------------------------------

CATEGORY_TO_EVAL_DIR = {
    "blocked": "flows",
    "scope_creep": "conventions",
}


def cluster_to_eval_spec(pattern: str, incidents: list[dict]) -> str:
    """Generate a .eval.md spec from a cluster."""
    categories = Counter(i.get("category", "unknown") for i in incidents)
    hooks = Counter(i.get("hook", "unknown") for i in incidents)
    tasks = Counter(i.get("task_id", "unknown") for i in incidents)
    severities = Counter(i.get("severity", "unknown") for i in incidents)
    date_range = sorted(set(i.get("date", "") for i in incidents))

    top_category = categories.most_common(1)[0][0]
    top_hook = hooks.most_common(1)[0][0]

    return dedent(f"""\
    # Eval: {pattern}

    > Auto-generated by incidents-to-evals.py from {len(incidents)} incidents.
    > Date range: {date_range[0] if date_range else 'unknown'} — {date_range[-1] if date_range else 'unknown'}
    > Source hook: {top_hook} | Category: {top_category} | Severity distribution: {dict(severities)}

    ## Should: Prevent "{pattern}" pattern
    - Input: Agent session where this failure pattern would occur
    - Expected: Hook or governance catches and prevents the failure
    - Fail if: Agent hits the same failure without prior escalation or mitigation

    ## Should: Detect early warning signals
    - Input: Session approaching the threshold that triggers this pattern
    - Expected: Agent self-corrects (runs tests, reduces scope) before hitting the limit
    - Fail if: Agent blindly iterates until the hook blocks

    ## Affected tasks
    {chr(10).join(f'- {task}: {count}x' for task, count in tasks.most_common(5))}

    ## Suggested test implementation
    - Add a pytest case in `evals/test_flows.py` that simulates the pre-conditions
    - Verify the hook fires correctly under those conditions
    - Verify agent behavior includes early self-correction
    """)


def slugify(text: str) -> str:
    """Convert pattern text to a filename slug."""
    slug = text.lower()
    slug = re.sub(r'[^a-z0-9]+', '-', slug)
    slug = slug.strip('-')
    return slug[:60]


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main():
    parser = argparse.ArgumentParser(description="Generate eval specs from incident clusters")
    parser.add_argument("--dry-run", action="store_true", help="Preview without writing files")
    parser.add_argument("--threshold", type=int, default=3, help="Min occurrences to flag (default: 3)")
    parser.add_argument("--json", action="store_true", help="Output cluster summary as JSON")
    args = parser.parse_args()

    incidents = load_incidents()
    if not incidents:
        print("No incidents found.", file=sys.stderr)
        sys.exit(0)

    clusters = cluster_incidents(incidents)

    # Filter to threshold
    flagged = {k: v for k, v in clusters.items() if len(v) >= args.threshold}

    if args.json:
        summary = []
        for pattern, incs in sorted(flagged.items(), key=lambda x: -len(x[1])):
            summary.append({
                "pattern": pattern,
                "count": len(incs),
                "categories": dict(Counter(i.get("category") for i in incs)),
                "hooks": dict(Counter(i.get("hook") for i in incs)),
                "tasks": dict(Counter(i.get("task_id") for i in incs)),
            })
        print(json.dumps(summary, indent=2))
        return

    print(f"Incidents: {len(incidents)} total, {len(clusters)} clusters, {len(flagged)} above threshold ({args.threshold}+)")
    print()

    generated = 0
    for pattern, incs in sorted(flagged.items(), key=lambda x: -len(x[1])):
        top_cat = Counter(i.get("category", "unknown") for i in incs).most_common(1)[0][0]
        eval_subdir = CATEGORY_TO_EVAL_DIR.get(top_cat, "flows")
        slug = slugify(pattern)
        filename = f"incident-{slug}.eval.md"
        target_dir = EVALS_DIR / eval_subdir
        target_path = target_dir / filename

        print(f"  {len(incs):3d}x  {pattern}")
        print(f"       → {target_path.relative_to(ROOT)}")

        if not args.dry_run:
            target_dir.mkdir(parents=True, exist_ok=True)
            spec = cluster_to_eval_spec(pattern, incs)
            target_path.write_text(spec)
            generated += 1

    print()
    if args.dry_run:
        print(f"Dry run — {len(flagged)} specs would be generated.")
    else:
        print(f"Generated {generated} eval specs.")


if __name__ == "__main__":
    main()
